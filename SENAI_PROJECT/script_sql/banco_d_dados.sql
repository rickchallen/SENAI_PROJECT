CREATE TABLE clubes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(60) NOT NULL,
    sigla CHAR(3) NOT NULL UNIQUE,
    caixa DECIMAL(10, 2) NOT NULL DEFAULT 300.00,
    formacao VARCHAR(5) CHECK (formacao IN ('3-1', '2-2', '2-1-1', '1-2-1')),
    criado_em TIMESTAMP NOT NULL
);

CREATE UNIQUE INDEX uq_clubes_nome_lower ON clubes (lower(nome));

CREATE TABLE jogadores (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    posicao VARCHAR(3) NOT NULL CHECK (posicao IN ('GOL', 'ZAG', 'LAT', 'MEI', 'ATA')),
    agilidade INTEGER NOT NULL CHECK (agilidade BETWEEN 1 AND 100),
    idade INTEGER NOT NULL CHECK (idade BETWEEN 16 AND 45),
    valor_base DECIMAL(6, 2) NOT NULL,
    condicao VARCHAR(20) NOT NULL CHECK (condicao IN ('APTO', 'MAL_CONDICIONADO', 'DOENTE')),
    clube_id INTEGER REFERENCES clubes(id),
    velocidade INTEGER NOT NULL CHECK (velocidade BETWEEN 1 AND 99),
    finalizacao INTEGER NOT NULL CHECK (finalizacao BETWEEN 1 AND 99),
    passe INTEGER NOT NULL CHECK (passe BETWEEN 1 AND 99),
    drible INTEGER NOT NULL CHECK (drible BETWEEN 1 AND 99),
    defesa INTEGER NOT NULL CHECK (defesa BETWEEN 1 AND 99),
    fisico INTEGER NOT NULL CHECK (fisico BETWEEN 1 AND 99),
    potencial INTEGER NOT NULL CHECK (potencial BETWEEN 1 AND 99),
    excluido_em TIMESTAMP,
    criado_em TIMESTAMP NOT NULL,
    atualizado_em TIMESTAMP NOT NULL,
    CHECK (idade < 35 OR agilidade <= 85)
);

CREATE TABLE contratos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jogador_id INTEGER NOT NULL REFERENCES jogadores(id),
    clube_id INTEGER NOT NULL REFERENCES clubes(id),
    valor_compra DECIMAL(6, 2) NOT NULL,
    fidelidade_ate TIMESTAMP NOT NULL,
    situacao VARCHAR(12) NOT NULL CHECK (situacao IN ('ATIVO', 'ENCERRADO', 'RESCINDIDO')),
    iniciado_em TIMESTAMP NOT NULL,
    encerrado_em TIMESTAMP
);

CREATE UNIQUE INDEX uq_contratos_jogador_ativo
    ON contratos (jogador_id)
    WHERE situacao = 'ATIVO';

CREATE TABLE transacoes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clube_id INTEGER NOT NULL REFERENCES clubes(id),
    jogador_id INTEGER NOT NULL REFERENCES jogadores(id),
    nome_jogador VARCHAR(100) NOT NULL,
    tipo VARCHAR(6) NOT NULL CHECK (tipo IN ('COMPRA', 'VENDA')),
    valor DECIMAL(6, 2) NOT NULL,
    taxa DECIMAL(6, 2) NOT NULL,
    multa DECIMAL(6, 2) NOT NULL DEFAULT 0.00,
    lucro DECIMAL(7, 2),
    variacao_caixa DECIMAL(8, 2) NOT NULL,
    criado_em TIMESTAMP NOT NULL
);

CREATE TABLE escalacoes (
    clube_id INTEGER NOT NULL REFERENCES clubes(id),
    jogador_id INTEGER NOT NULL UNIQUE REFERENCES jogadores(id),
    criado_em TIMESTAMP NOT NULL,
    PRIMARY KEY (clube_id, jogador_id)
);

CREATE TABLE partidas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mandante_id INTEGER NOT NULL REFERENCES clubes(id),
    visitante_id INTEGER NOT NULL REFERENCES clubes(id),
    gols_mandante INTEGER NOT NULL CHECK (gols_mandante BETWEEN 0 AND 3),
    gols_visitante INTEGER NOT NULL CHECK (gols_visitante BETWEEN 0 AND 3),
    formacao_mandante VARCHAR(5) NOT NULL CHECK (formacao_mandante IN ('3-1', '2-2', '2-1-1', '1-2-1')),
    formacao_visitante VARCHAR(5) NOT NULL CHECK (formacao_visitante IN ('3-1', '2-2', '2-1-1', '1-2-1')),
    jogada_em TIMESTAMP NOT NULL,
    CHECK (mandante_id <> visitante_id)
);

CREATE TABLE duelos_partida (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partida_id INTEGER NOT NULL REFERENCES partidas(id),
    ordem INTEGER NOT NULL CHECK (ordem BETWEEN 1 AND 6),
    clube_atacante_id INTEGER NOT NULL REFERENCES clubes(id),
    atacante_id INTEGER NOT NULL REFERENCES jogadores(id),
    defensor_id INTEGER NOT NULL REFERENCES jogadores(id),
    nome_atacante VARCHAR(100) NOT NULL,
    nome_defensor VARCHAR(100) NOT NULL,
    posicao_atacante VARCHAR(3) NOT NULL,
    posicao_defensor VARCHAR(3) NOT NULL,
    condicao_atacante VARCHAR(20) NOT NULL CHECK (condicao_atacante IN ('APTO', 'MAL_CONDICIONADO')),
    condicao_defensor VARCHAR(20) NOT NULL CHECK (condicao_defensor IN ('APTO', 'MAL_CONDICIONADO')),
    atributo_ataque VARCHAR(10) NOT NULL CHECK (atributo_ataque IN ('shooting', 'passing', 'dribbling', 'defending')),
    atributo_defesa VARCHAR(10) NOT NULL CHECK (atributo_defesa IN ('shooting', 'passing', 'dribbling', 'defending')),
    valor_ataque INTEGER NOT NULL,
    valor_defesa INTEGER NOT NULL,
    gol BOOLEAN NOT NULL,
    UNIQUE (partida_id, ordem)
);
